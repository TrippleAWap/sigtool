//! Spec-level constants.
//!
//! Every value here is part of the signature spec. Changing a bucket boundary,
//! a hash person string, or a string-length limit changes feature records and
//! therefore requires bumping `SPEC_VERSION` and editing `spec/`.

use blake2b_simd::Params;

pub const SPEC_VERSION: &str = "2";

/// blake2b personalization fixes the hash domain; the Python reference uses
/// `hashlib.blake2b(..., person=b"sigtool.v1")`.
pub const HASH_PERSON: &[u8; 16] = b"sigtool.v1\0\0\0\0\0\0";
pub const HASH_DIGEST_SIZE: usize = 16;

/// Bucket index = number of bounds <= value - 1, so a value of 0 lands in
/// bucket 0 and anything above the last bound lands in the last bucket.
pub const BUCKET_BOUNDS: [usize; 15] = [0, 1, 2, 3, 4, 6, 9, 13, 19, 28, 40, 60, 90, 135, 200];

pub const STR_MIN_LEN: usize = 4;
pub const STR_MAX_LEN: usize = 120;

// Recovery budgets. These bound work on untrusted, possibly-random bytes.
pub const MAX_FUNCTION_BYTES: u64 = 0x1_0000;
pub const MAX_BLOCK_BYTES: u64 = 0x1000;
pub const MAX_INSTRUCTIONS: usize = 20_000;
pub const MAX_BLOCKS: usize = 512;
pub const MAX_READ_BYTES: usize = 0x1_0000;
pub const MAX_THUNK_HOPS: usize = 4;

/// Return the spec-defined hex digest used for over-long feature values.
///
/// Python encodes with `surrogatepass`; feature values are valid UTF-8 in
/// practice, so the byte form is identical.
pub fn digest(text: &str) -> String {
    let mut params = Params::new();
    params.hash_length(HASH_DIGEST_SIZE).personal(HASH_PERSON);
    let hash = params.hash(text.as_bytes());
    hex(hash.as_bytes())
}

/// Map a count to its bucket index (see [`BUCKET_BOUNDS`]).
pub fn bucket(value: usize) -> usize {
    if value == 0 {
        return 0;
    }
    for (index, bound) in BUCKET_BOUNDS.iter().enumerate() {
        if value <= *bound {
            return index;
        }
    }
    BUCKET_BOUNDS.len() - 1
}

/// Return the `(low, high)` range covered by a bucket (`high = None`: open).
pub fn bucket_range(index: usize) -> (usize, Option<usize>) {
    if index == 0 {
        return (0, Some(BUCKET_BOUNDS[0]));
    }
    if index >= BUCKET_BOUNDS.len() - 1 {
        return (BUCKET_BOUNDS[BUCKET_BOUNDS.len() - 2] + 1, None);
    }
    (BUCKET_BOUNDS[index - 1] + 1, Some(BUCKET_BOUNDS[index]))
}

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(char::from_digit((byte >> 4) as u32, 16).expect("nibble"));
        out.push(char::from_digit((byte & 0xF) as u32, 16).expect("nibble"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn digest_matches_python_reference() {
        // Generated by the Python reference: digest("hello").
        assert_eq!(digest("hello"), "6b8bb66bcdb914d9972f9157622587b7");
        assert_eq!(digest("abc"), "200db5eb762b7c64916147b3a19acafa");
    }

    #[test]
    fn buckets_cover_boundaries() {
        assert_eq!(bucket(0), 0);
        assert_eq!(bucket(1), 1);
        assert_eq!(bucket(2), 2);
        assert_eq!(bucket(4), 4);
        assert_eq!(bucket(5), 5);
        assert_eq!(bucket(201), 14);
    }
}
